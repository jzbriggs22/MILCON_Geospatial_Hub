"""Generate sql/views_and_functions.sql from the executable SQL constants.

The reference file exists so auditors can read every piece of SQL in one
place.  It is GENERATED from the single sources of truth (the migration
module and app/analytics/queries.py) — never edit it by hand.
tests/test_sql_reference.py fails if the file is stale.

Regenerate with:
    python -m app.db.generate_sql_reference
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

from app.analytics import queries

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
OUTPUT_PATH = REPO_ROOT / "sql" / "views_and_functions.sql"
MIGRATION_002 = REPO_ROOT / "app" / "db" / "migrations" / "versions" / "002_materialized_views.py"

HEADER = """\
-- ==========================================================================
-- MILCON Geospatial Hub — SQL reference (GENERATED FILE, do not edit)
-- ==========================================================================
-- Generated by: python -m app.db.generate_sql_reference
-- Sources of truth:
--   app/db/migrations/versions/002_materialized_views.py  (view definitions)
--   app/analytics/queries.py                              (analytic queries)
-- tests/test_sql_reference.py fails if this file is out of date.
-- ==========================================================================
"""


def load_migration_module():
    spec = importlib.util.spec_from_file_location("migration_002", MIGRATION_002)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render_reference() -> str:
    mig = load_migration_module()
    sections = [
        HEADER,
        "-- Materialized view: project_hazard_proximity",
        "-- Pairwise project<->hazard distances in meters (geography), capped at",
        f"-- {mig.MAX_PROXIMITY_RADIUS_M} m.  Scenario buffers filter on distance_m at query time.",
        mig.MV_HAZARD_PROXIMITY.strip() + ";",
        "",
        "-- Materialized view: project_constraint_proximity",
        mig.MV_CONSTRAINT_PROXIMITY.strip() + ";",
        "",
        "-- Refresh statements (single source of truth: app/analytics/queries.py;",
        "-- executed via app.db.maintenance.refresh_analytics_views)",
    ]
    sections += [stmt + ";" for stmt in queries.REFRESH_STATEMENTS]
    sections += [
        "",
        "-- ==========================================================================",
        "-- RAW_FACTORS_QUERY — the scoring query executed by app/analytics/scoring.py",
        "-- Bind parameters: :year, :hazard_buffer_m, :constraint_buffer_m",
        "-- ==========================================================================",
        "-- " + "\n-- ".join(queries.RAW_FACTORS_QUERY.strip().splitlines()),
        "",
    ]
    return "\n".join(sections)


def main() -> None:
    OUTPUT_PATH.write_text(render_reference())
    print(f"Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
